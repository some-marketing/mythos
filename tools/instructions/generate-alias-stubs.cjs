#!/usr/bin/env node
// Generate .claude/commands/<alias>.md stubs from the canonical alias registry.
//
// The registry (instructions/canonical/command-aliases.yaml) is the authority;
// a stub is presentation. Per the alias-authority law, a stub that no registry
// entry produced is a lie about where it came from — so stubs for new aliases
// are emitted by this tool from the registry entry, never hand-written.
//
// Behavior:
//   --check           list aliases whose stub is missing (exit 1 if any), write nothing
//   --emit <alias>    emit the stub for one alias (must be missing, target .md must exist)
//   --emit-missing    emit stubs for every missing alias whose target .md exists
//
// This tool NEVER overwrites an existing stub: pre-existing stubs (gm.md,
// scry.md, …) were authored alongside their registry entries and may carry
// wording this template does not reproduce. Regeneration of an existing stub
// is a deliberate act — delete the file first, then emit.

const fs = require('fs');
const path = require('path');
const { loadAliasRegistry } = require('../commands/lib/command-aliases.cjs');

const ROOT = path.resolve(__dirname, '..', '..');
const COMMANDS_DIR = path.join(ROOT, '.claude', 'commands');
const REGISTRY_PATH = 'instructions/canonical/command-aliases.yaml';

const STATUS_PHRASE = {
  primary: 'the short form',
  'cross-alias': 'a cross-alias',
  compatibility: 'a compatibility alias',
};

const STATUS_DESCRIPTION = {
  primary: 'Short form of',
  'cross-alias': 'Cross-alias for',
  compatibility: 'Compatibility alias for',
};

function renderStub(alias, target, status) {
  const phrase = STATUS_PHRASE[status] || 'an alias';
  const desc = STATUS_DESCRIPTION[status] || 'Alias for';
  return `---
description: ${desc} /${target}
allowed-tools: [Read, Write, Edit, Glob, Grep, Bash, Task]
---

<!-- Generated by tools/instructions/generate-alias-stubs.cjs from the
     \`${alias}\` entry in ${REGISTRY_PATH}. The registry entry is the
     authority; do not hand-edit this stub — change the registry and
     regenerate. -->

<objective>
Run \`/${target}\`. \`${alias}\` is ${phrase}; the full command body lives under \`.claude/commands/${target}.md\`.
</objective>

<process>
1. Follow \`.claude/commands/${target}.md\`.
</process>

<success_criteria>
- \`/${alias}\` resolves to the same behavior as \`/${target}\`
</success_criteria>
`;
}

function collectAliases() {
  const registry = loadAliasRegistry(ROOT).aliases || [];
  return registry.map((entry) => {
    const alias = entry.id;
    const target = entry.target;
    const status = entry.status || 'primary';
    const stubPath = path.join(COMMANDS_DIR, `${alias}.md`);
    const targetPath = path.join(COMMANDS_DIR, `${target}.md`);
    return {
      alias,
      target,
      status,
      stubPath,
      stubExists: fs.existsSync(stubPath),
      targetExists: fs.existsSync(targetPath),
    };
  });
}

function emit(entry) {
  if (entry.stubExists) {
    console.error(`refuse: ${entry.alias} — stub already exists at ${entry.stubPath}; delete it first if regeneration is intended`);
    return false;
  }
  if (!entry.targetExists) {
    console.error(`refuse: ${entry.alias} — target .claude/commands/${entry.target}.md does not exist (catalog membership fails); fix the registry or land the target first`);
    return false;
  }
  fs.writeFileSync(entry.stubPath, renderStub(entry.alias, entry.target, entry.status));
  const readBack = fs.readFileSync(entry.stubPath, 'utf8');
  const ok = readBack.includes(`/${entry.target}\``);
  console.log(`emitted: ${entry.stubPath} (read-back ${ok ? 'ok' : 'FAILED'})`);
  return ok;
}

function main(argv) {
  const entries = collectAliases();
  if (entries.length === 0) {
    console.error(`no aliases loaded from ${REGISTRY_PATH}`);
    return 2;
  }
  const missing = entries.filter((e) => !e.stubExists);

  if (argv.includes('--check')) {
    for (const e of missing) {
      console.log(`missing: ${e.alias} -> ${e.target} [${e.status}]${e.targetExists ? '' : ' (target .md ALSO missing)'}`);
    }
    if (missing.length === 0) console.log('all registry aliases have stubs');
    return missing.length === 0 ? 0 : 1;
  }

  const emitIdx = argv.indexOf('--emit');
  if (emitIdx !== -1) {
    const name = argv[emitIdx + 1];
    const entry = entries.find((e) => e.alias === name);
    if (!entry) {
      console.error(`refuse: no alias "${name}" in ${REGISTRY_PATH} — the registry is the authority; add the entry there first`);
      return 1;
    }
    return emit(entry) ? 0 : 1;
  }

  if (argv.includes('--emit-missing')) {
    let failures = 0;
    for (const e of missing) {
      if (!emit(e)) failures += 1;
    }
    console.log(`${missing.length - failures}/${missing.length} missing stubs emitted`);
    return failures === 0 ? 0 : 1;
  }

  console.error('usage: generate-alias-stubs.cjs --check | --emit <alias> | --emit-missing');
  return 2;
}

process.exit(main(process.argv.slice(2)));
