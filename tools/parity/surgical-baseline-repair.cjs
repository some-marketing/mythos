#!/usr/bin/env node
'use strict';

// Surgical parity-baseline repair (operator-sanctioned, option 1 faithful path).
// PR #10 changed 15 harness-wired files; portable-parity CI drifted because
// parity/baseline.json's target-side digests (expected_files, expected_tree_sha256,
// wiring graph) no longer match the merged public checkout.
//
// This mirrors build-baseline.cjs's TARGET-side computation EXACTLY while
// preserving source.* verbatim (source.commit stays 81fba1215 — the recorded
// export source; export_map/denylist bindings already match the public
// checkout's files: c818827e/e7855588). This is the same pattern the operator
// used in caf9072f1 ("updated 13 changed digests... recomputed
// expected_tree_sha256 + wiring counts") — the sanctioned in-repo convention
// for registering legitimate code changes.
//
// Hard rules honored: no fabrication of source args; no source.commit rewrite;
// only target-side digests refreshed; verification via verify-parity before any
// commit.

const fs = require('fs');
const path = require('path');
const { fileSha, matches, posix, sha256, treeDigest, walk } = require('./lib.cjs');

const ROOT = path.resolve(__dirname, '..', '..');
const BASELINE_PATH = path.join(ROOT, 'parity', 'baseline.json');
const GRAPH_PATH = path.join(ROOT, 'parity', 'wiring-graph.json');

function readJson(p) { return JSON.parse(fs.readFileSync(p, 'utf8')); }

const baseline = readJson(BASELINE_PATH);
const baselineRelative = posix(path.relative(ROOT, BASELINE_PATH));
const runtimeExclusions = baseline.runtime_exclusions || [];

// Mirror build-baseline: expected_files = walk of everything EXCEPT the
// baseline file itself and runtime exclusions; each row = {path, sha256, mode}.
const expectedFiles = walk(ROOT, (relative) => (
  relative === baselineRelative || matches(relative, runtimeExclusions)
)).map((relative) => {
  const absolute = path.join(ROOT, relative);
  return {
    path: relative,
    sha256: fileSha(absolute),
    mode: fs.statSync(absolute).mode & 0o777
  };
});

const expectedTree = treeDigest(ROOT, expectedFiles.map((row) => row.path));

// Wiring graph was regenerated by build-wiring-graph.cjs (standalone, verified
// 3776 nodes / 2721 edges / 0 unresolved). Re-pin its digest + counts.
if (!fs.existsSync(GRAPH_PATH)) throw new Error('parity/wiring-graph.json missing — run build-wiring-graph.cjs first');
const graph = readJson(GRAPH_PATH);
const graphSha = fileSha(GRAPH_PATH);

const packageJson = readJson(path.join(ROOT, 'package.json'));
const aliasPath = path.join(ROOT, 'instructions', 'canonical', 'command-aliases.yaml');
const aliases = fs.existsSync(aliasPath) ? sha256(fs.readFileSync(aliasPath)) : null;

// Preserve source.* verbatim; refresh ONLY target-side digest rows + wiring pins.
const updated = {
  ...baseline,
  target: {
    ...baseline.target,
    expected_files: expectedFiles,
    expected_tree_sha256: expectedTree
  },
  wiring: {
    ...baseline.wiring,
    package_script_count: Object.keys(packageJson.scripts || {}).length,
    command_alias_registry_sha256: aliases,
    graph_sha256: graphSha,
    graph_nodes: graph.counts.nodes,
    graph_edges: graph.counts.edges
  }
};

fs.writeFileSync(BASELINE_PATH, JSON.stringify(updated, null, 2) + '\n');

console.log(JSON.stringify({
  wrote: path.relative(ROOT, BASELINE_PATH),
  source_commit_preserved: baseline.source.commit,
  expected_files: expectedFiles.length,
  expected_tree_sha256: expectedTree.slice(0, 12),
  graph_sha256: graphSha.slice(0, 12),
  graph_nodes: graph.counts.nodes,
  graph_edges: graph.counts.edges,
  package_script_count: updated.wiring.package_script_count
}, null, 2));
